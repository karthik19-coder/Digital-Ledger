-- Phase 12B.1: RLS Helper Functions and Indexes

-- 1. Helper Functions
-- ==========================================

-- A. is_owner()
CREATE OR REPLACE FUNCTION public.is_owner()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT
    auth.uid() IS NOT NULL
    AND EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE id = auth.uid() AND role = 'owner'
    );
$$;

-- SECURITY DEFINER
-- Reads authorization information from public.profiles.
-- Used exclusively by RLS policies.
COMMENT ON FUNCTION public.is_owner()
IS 'Returns TRUE if the authenticated user has the owner role.';

REVOKE ALL ON FUNCTION public.is_owner() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_owner() TO authenticated;
GRANT EXECUTE ON FUNCTION public.is_owner() TO service_role;


